"""Renders results/SUMMARY.md from the experiment outputs."""
from __future__ import annotations

from collections import Counter
from pathlib import Path


def _md_table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")).replace("|", "\\|") for c in cols) + " |")
    return "\n".join(out)


def _status_B(agB, cid):
    r = agB.results.get(cid)
    if not r:
        return "not attempted"
    if r["status"] == "proved":
        b = r["attempts"][-1]["budget"]
        return f"⊢ (kernel; budget {b})"
    if r["status"] == "refuted":
        return "⊢ ¬ (kernel)"
    return "unproven (search failed)"


def _status_A(agA, cid):
    r = agA.results.get(cid)
    if not r:
        return "not attempted"
    if r["status"] == "inexpressible":
        return "inexpressible"
    if r["status"] == "decided":
        s = "⊢" if r["decided"] else "⊢ ¬"
        return f"{s} ({'kernel' if r.get('kernel_proof') else 'decided'})"
    return r["status"]


def discovery_measures(tr):
    ids = {c["cid"]: c for c in tr["claims"]}
    cats = Counter(c["category"] for c in tr["claims"])
    naive_overclaims = [c["cid"] for c in tr["claims"] if c["category"] == "unprovability"]
    m = {}
    m["1 identifies hard/impossible statements"] = (
        "yes" if any(c["category"] in ("status", "unprovability", "expressiveness") for c in tr["claims"]) else "no")
    if naive_overclaims:
        m["2 distinguishes unproven vs unprovable"] = f"NO ({len(naive_overclaims)} unprovability claims from failed search)"
    elif "B-L3" in ids:
        m["2 distinguishes unproven vs unprovable"] = "yes, and proves it cannot do so unconditionally (B-L3)"
    elif any(c["category"] == "status" for c in tr["claims"]):
        m["2 distinguishes unproven vs unprovable"] = "partially (reports 'unproven', has no tool for 'unprovable')"
    elif tr["world"] == "World-A":
        m["2 distinguishes unproven vs unprovable"] = "n/a in practice (everything decided)"
    else:
        m["2 distinguishes unproven vs unprovable"] = "—"
    m["3 recognizes expressive limitations"] = ("yes" if any(k in ids for k in ("A-nondef", "A-nomul", "B-L7"))
                                                else "no")
    m["4 recognizes incompleteness"] = ("yes (conditional, exact assumptions)" if "B-L5" in ids
                                        else ("correctly finds none" if "A-complete" in ids else "no"))
    m["5 formulates stronger-framework possibility"] = ("yes (precise)" if "B-HP2" in ids
                                                        else ("only speculatively" if "A-HA2" in ids else "no"))
    m["6 identifies required assumptions"] = ("yes (Con, Con², tower)" if "B-HP3" in ids else "no")
    return m


def write_summary(R: Path, trA, runs, abl, trC, controls, xchecks, grades, lean, agA, agB):
    L = ["# Results summary (generated by `python -m nfl.experiments.run_all`)", ""]

    # ---- table of what each environment can establish
    L += ["## 1. What each environment can establish", "",
          "A = Presburger arithmetic (agent A, own kernel + decision procedure); B = Peano arithmetic (agent B, "
          "own kernel); C = parent (Lean 4 + metatools). '⊢' = established, 'decided' = by decision procedure, "
          "'kernel' = by a kernel-checked derivation.", ""]
    rows = [
        {"statement": "2 + 3 = 5 / 2 + 2 = 4", "A": _status_A(agA, "a1"), "B": _status_B(agB, "b1"),
         "C": "⊢ (true Δ0)"},
        {"statement": "∀x∀y x+y = y+x", "A": _status_A(agA, "a3"), "B": "⊢ (kernel, self-generated lemma)",
         "C": "⊢"},
        {"statement": "∀x>7 ∃a,b x = 3a+5b", "A": _status_A(agA, "a4"), "B": "not attempted (provable)",
         "C": "⊢"},
        {"statement": "17·23 = 391", "A": _status_A(agA, "a9"), "B": _status_B(agB, "b2"), "C": "⊢"},
        {"statement": "∀x∀y x·y = y·x", "A": "inexpressible", "B": _status_B(agB, "b7"),
         "C": "⊢ (B's proof replayed in Lean)" if lean.get("build_ok") else "⊢"},
        {"statement": "∀x,y,z (xy)z = x(yz)", "A": "inexpressible", "B": _status_B(agB, "b9"), "C": "⊢"},
        {"statement": "∀x∀y (x+y=0 → x=0)", "A": _status_A(agA, "a11"), "B": _status_B(agB, "b10"),
         "C": "true; PA-provable"},
        {"statement": "√2 irrational (b11)", "A": "inexpressible", "B": _status_B(agB, "b11"),
         "C": "true; PA-provable (not mechanized here)"},
        {"statement": "infinitely many primes (b12)", "A": _status_A(agA, "a10"), "B": _status_B(agB, "b12"),
         "C": "true; PA-provable (not mechanized here)"},
        {"statement": "Goldbach (b13), twin primes (b14)", "A": "inexpressible",
         "B": f"{_status_B(agB, 'b13')}; {_status_B(agB, 'b14')}", "C": "unknown (open problems)"},
        {"statement": "squares / primes / × definable?", "A": "⊢ not definable (decided + argument)",
         "B": "definable", "C": "—"},
        {"statement": "'my theory is complete'", "A": "asserted, conditional; NOT expressible in A",
         "B": "B is not complete (conditional on Con²)", "C": "A complete (Presburger); B incomplete"},
        {"statement": "Con(B)", "A": "inexpressible", "B": "⊬ (if Con B); only 'Con B → …' internally",
         "C": "⊢ (Lean: NL.consistent)" if lean.get("build_ok") else "⊢"},
        {"statement": "Gödel sentence G_B (≡ Con B)", "A": "inexpressible",
         "B": "independent if Con(B + Con B) (conditional)", "C": "⊢ G_B true"},
        {"statement": "Con(B) → B ⊬ G_B", "A": "inexpressible", "B": "⊢ (internal, via GL)", "C": "⊢"},
        {"statement": "'B ⊬ G_B' (unconditionally)", "A": "inexpressible",
         "B": "cannot be proved by B unless B is inconsistent (B-L3)", "C": "⊢ (relative to C's foundations)"},
        {"statement": "Goodstein's theorem", "A": "inexpressible", "B": "⊬ (Kirby-Paris; not attempted)",
         "C": "true (cited); seeds 1-3 computed"},
        {"statement": "Con(C)", "A": "—", "B": "—", "C": "⊬ (Gödel II, if C consistent)"},
    ]
    L += [_md_table(rows, ["statement", "A", "B", "C"]), ""]

    # ---- discovery measures
    L += ["## 2. Discovery-challenge measures (Part 3)", ""]
    dm = {"Agent A": discovery_measures(trA), "Agent B": discovery_measures(runs["P1"]),
          "B without meta toolkit": discovery_measures(abl["nometa"]),
          "B naive (failed search ⇒ 'unprovable')": discovery_measures(abl["naive"])}
    keys = list(next(iter(dm.values())).keys())
    rows = [{"measure": k, **{a: dm[a][k] for a in dm}} for k in keys]
    L += [_md_table(rows, ["measure"] + list(dm)), ""]

    # ---- grades
    L += ["## 3. Controller grading of every claim", ""]
    gc = {}
    for g in grades:
        key = f"{g['agent']} [{g['implementation']}]"
        if g["agent"] == runs["P1"]["agent"] and g["implementation"] == "P1":
            n_claims = len(runs["P1"]["claims"])
            # distinguish full agent from ablations by claim count
        gc.setdefault(key, Counter())[g["grade"]] += 1
    rows = [{"agent [parent]": k, **{gg: v.get(gg, 0) for gg in
             ("CORRECT", "CORRECT (conditional)", "INCORRECT", "UNSUPPORTED", "NOT GRADED (speculation)",
              "UNGRADED")}} for k, v in gc.items()]
    L += [_md_table(rows, ["agent [parent]", "CORRECT", "CORRECT (conditional)", "INCORRECT", "UNSUPPORTED",
                           "NOT GRADED (speculation)", "UNGRADED"]), "",
          "Per-claim grades with their basis: results/grades.json.", ""]
    bad = [g for g in grades if g["grade"] in ("INCORRECT", "UNSUPPORTED")]
    if bad:
        L += ["Incorrect / unsupported claims:", ""]
        for g in bad:
            L.append(f"- {g['agent']} [{g['implementation']}] {g['claim']}: {g['grade']} -- {g['basis']}")
        L.append("")

    # ---- parents
    L += ["## 4. Parents of the same child (Part 4, controls 3-4)", "",
          "What each candidate parent proves about letterless provability sentences of B:", ""]
    kt = controls["parent_knowledge_table"]
    L += [_md_table(kt, ["sentence", "formal", "true_in_N_if_B_sound", "C_lean", "C_opt", "C_pess", "C_con2",
                         "C_impl"]), ""]
    L += ["Self-consistency of each parent:", ""]
    for k, v in controls["parent_self_consistency"].items():
        L.append(f"- **{k}**: own consistency: {v['own']}; {v['consistent_if']}")
    inv = controls["implementation_invariance"]
    L += ["", f"Implementation invariance: transcript sha256 under P1 = `{inv['P1'][:16]}…`, under P2 = "
          f"`{inv['P2'][:16]}…` → identical: **{inv['identical']}**; under P3 (unfaithful) = `{inv['P3'][:16]}…` "
          f"→ differs: **{inv['P3_differs']}**.", ""]

    # ---- extensions
    L += ["## 5. Extending the child (control 5)", ""]
    ext = [r for r in controls["extensions"] if "goedel_sentence_provable" in r]
    L += [_md_table(ext, ["theory", "own_consistency_equiv_Con^", "proves_own_consistency",
                          "goedel_sentence_equiv_own_consistency", "goedel_sentence_provable",
                          "unprovability_needs"]), ""]
    for r in controls["extensions"]:
        if "proves_own_inconsistency" in r:
            L.append(f"- **{r['theory']}**: proves its own inconsistency: {r['proves_own_inconsistency']}; "
                     f"consistent given {r['consistent_given']}.")
    L.append("")

    # ---- control 6
    L += ["## 6. Truth vs provability vs computation vs search (control 6)", ""]
    sweep = controls["budget_sweep_B"]
    def found(cid):
        r = agB.results.get(cid, {})
        return "yes" if r.get("status") == "proved" else "no"
    rows = [
        {"statement": "17·23 = 391", "true?": "yes", "PA-provable?": "yes", "found by B": found("b2"),
         "feasible?": "yes", "lesson": "Δ0 truths are mechanically provable"},
        {"statement": "∀xyz (xy)z = x(yz)", "true?": "yes", "PA-provable?": "yes", "found by B": found("b9"),
         "feasible?": "yes", "lesson": f"attempts: {[(a['budget'], a['status']) for a in sweep.get('b9', [])]}"},
        {"statement": "∀xy (x+y=0 → x=0)", "true?": "yes", "PA-provable?": "yes", "found by B": found("b10"),
         "feasible?": "yes", "lesson": "provable, but outside the prover's tactics: failure ≠ unprovability"},
        {"statement": "∀n ∃p>n prime", "true?": "yes", "PA-provable?": "yes", "found by B": found("b12"),
         "feasible?": "yes", "lesson": "same"},
        {"statement": "Goldbach", "true?": "unknown", "PA-provable?": "unknown", "found by B": found("b13"),
         "feasible?": "bounded instances only", "lesson": "no method distinguishes 'hard' from 'independent'"},
        {"statement": "Goodstein(4) terminates", "true?": "yes", "PA-provable?": "yes (true Σ1)",
         "found by B": "no", "feasible?": "NO (≈3·2^402653211 steps)", "lesson": "provable ≠ feasibly provable"},
        {"statement": "Goodstein's theorem", "true?": "yes", "PA-provable?": "no (Kirby-Paris)", "found by B": "no",
         "feasible?": "—", "lesson": "natural independence; invisible to B's tools"},
        {"statement": "Con(B), G_B", "true?": "yes (Lean)", "PA-provable?": "no (Gödel)", "found by B": "no",
         "feasible?": "—", "lesson": "B identifies these, but only conditionally"},
    ]
    L += [_md_table(rows, ["statement", "true?", "PA-provable?", "found by B", "feasible?", "lesson"]), ""]
    sv = controls.get("search_vs_provability", [])
    if sv:
        L += ["Same true, PA-provable identities under different search states (rewrite-step budget × induction "
              "depth × prior knowledge). Every cell is a statement that IS provable; 'not found' cells are "
              "artefacts of the searcher:", ""]
        cols = list(sv[0].keys())
        L += [_md_table(sv, cols), ""]

    # ---- cross-checks
    L += ["## 7. Verification of the tools (Part 6)", ""]
    x1 = xchecks["X1_cooper_vs_z3"]
    L.append(f"- **Cooper vs Z3**: {x1}")
    for k in ("X2_kernels_B", "X2_kernels_A"):
        L.append(f"- **{k}**: {xchecks[k]}")
    x3 = xchecks["X3_gl"]
    L.append(f"- **GL tableau**: {x3}")
    L.append(f"- **Lean**: build ok = {lean.get('build_ok')}, replayed theorems = {lean.get('replayed')}, "
             f"axiom correspondence checks = {lean.get('axiom_checks')}, `#print axioms` = {lean.get('axioms')}")
    L.append("")
    (R / "SUMMARY.md").write_text("\n".join(L))
